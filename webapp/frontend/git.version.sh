#!/usr/bin/env bash

# logs go to stderr so `--print` (used by the Makefile) only writes the version to stdout

SEMVER_TAG_REGEX='^v[0-9]+\.[0-9]+\.[0-9]+$'

GIT_TAG="$(git describe --tags --exact-match 2>/dev/null)"

if [[ "${GIT_TAG}" =~ ${SEMVER_TAG_REGEX} ]]; then
    echo "generating version file from the checked out release tag" >&2
    VERSION_INFO="${GIT_TAG}"
else
    if [[ -n "${GIT_TAG}" ]]; then
        echo "ignoring tag ${GIT_TAG}, it is not a release version" >&2
    fi

    GIT_BRANCH="$(git rev-parse --abbrev-ref HEAD)"
    if [[ "${GIT_BRANCH}" == "HEAD" ]]; then
        # detached at an untagged commit, so git has no name for it
        GIT_BRANCH="${GITHUB_REF_NAME:-detached}"
    fi

    echo "no release tag on the checked out commit, generating version file from the branch" >&2
    VERSION_INFO="${GIT_BRANCH}#$(git rev-parse --short=7 HEAD)"
fi

if [[ "$1" == "--print" ]]; then
    echo "${VERSION_INFO}"
    exit
fi

# lets CI pass the same version to the docker builds, which have no .git to read it from
if [[ -n "${GITHUB_OUTPUT}" ]]; then
    echo "version=${VERSION_INFO}" >> "${GITHUB_OUTPUT}"
fi

echo "writing version file (version: ${VERSION_INFO})" >&2
cat <<EOT > src/environments/versions.ts
// this file is automatically generated by git.version.ts script
export const versionInfo = {
    version: '${VERSION_INFO}',
};
EOT
